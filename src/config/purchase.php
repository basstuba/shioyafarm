<?php

/**
 * 購入完了処理の設定
 */
return [
    /** 購入完了処理の排他ロックを待つ秒数（同時リクエストはこの間待ってから結果を確認する） */
    'complete_lock_wait' => 5,

    /** 購入完了処理の排他ロックの有効秒数（処理が異常終了してもこの時間で解放される。Stripe への問い合わせ1回分の最大秒数 services.stripe.timeout を上回る値にする） */
    'complete_lock_ttl' => 30,

    /** 「注文を確定する」の排他ロックを待つ秒数（同時に届いた再送信は、この間待ってからトークンを確認する。待っても取れなければ「処理中」のエラーにする） */
    'begin_lock_wait' => 10,

    /**
     * 「注文を確定する」の排他ロックの有効秒数（処理が異常終了してもこの時間で解放される）
     *
     * 1回の注文確定で起こりうる Stripe への問い合わせの最大回数（begin_stripe_calls）× 1回あたりの最大秒数（services.stripe.timeout）を上回る値にする。
     * 処理の途中でロックが切れると、別のリクエストが同時に同じ処理を始めてしまう。
     */
    'begin_lock_ttl' => 180,

    /**
     * 1回の注文確定で起こりうる Stripe への問い合わせの最大回数
     *
     * 前の注文の片づけ（キャンセル→状態確認→入金確認の保存で3回、または状態確認→失効→再確認→支払い確認の保存で4回）、
     * Customer の用意（2回）、銀行振込の PaymentIntent の作成と取り消し（2回）を合わせた最大の8回。
     */
    'begin_stripe_calls' => 8,

    /** 「注文を確定する」を同じ会員・同じセッションで同時に受け付けない（セッションの排他）ときに、先のリクエストの終了を待つ秒数 */
    'session_lock_wait' => 15,

    /** 注文トークン（購入ページを開くたびに発行する、1回限りのトークン）の有効分数 */
    'order_token_ttl_minutes' => 120,

    /** 購入データを保存した注文の記録を残す日数（同時リクエストの二重保存の検知用） */
    'completed_marker_days' => 1,
];
